import { CATEGORIES, CONTACT_DATA, PRODUCTS, type Product } from './data';

export const SITE_URL = (process.env.NEXT_PUBLIC_SITE_URL || 'https://srindustries.info').replace(/\/$/, '');
export const SITE_NAME = 'SR Industries';
export const FOUNDED = '2013';

export const PHONE_HREF = `tel:${CONTACT_DATA.phone.replace(/\s/g, '')}`;
export const WHATSAPP_HREF = `https://wa.me/${CONTACT_DATA.whatsapp}`;

export function whatsappLink(text: string) {
  return `${WHATSAPP_HREF}?text=${encodeURIComponent(text)}`;
}

export function getProduct(slug: string) {
  return PRODUCTS.find((p) => p.slug === slug);
}

export function getCategory(slug: string) {
  return CATEGORIES.find((c) => c.slug === slug);
}

/** Short, human category names used in labels. */
export const CATEGORY_LABEL: Record<Product['category'], string> = {
  knobs: 'Knobs',
  'dial-plates': 'Dial plates',
  legs: 'Stove legs',
  'coupler-pins': 'Couplers and pins',
  'auto-safety': 'Auto and safety parts',
};

export function priceSummary(product: Product): string | null {
  if (product.priceRange) return `₹${product.priceRange.min}–${product.priceRange.max}`;
  const prices = (product.colorVariants ?? [])
    .map((v) => v.price)
    .filter((p): p is number => p !== undefined);
  if (prices.length) {
    const min = Math.min(...prices);
    const max = Math.max(...prices);
    return min === max ? `₹${fmt(min)}` : `₹${fmt(min)}–${fmt(max)}`;
  }
  if (product.price !== undefined) return `₹${fmt(product.price)}`;
  return null;
}

export function lowestPrice(product: Product): number | undefined {
  if (product.priceRange) return product.priceRange.min;
  const prices = (product.colorVariants ?? [])
    .map((v) => v.price)
    .filter((p): p is number => p !== undefined);
  if (prices.length) return Math.min(...prices);
  return product.price;
}

export function fmt(n: number) {
  return n.toFixed(2);
}

export function specLabel(key: string) {
  const map: Record<string, string> = {
    shaftSize: 'Shaft size',
    diameter: 'Diameter',
    weight: 'Weight',
    material: 'Material',
    height: 'Height',
    type: 'Type',
  };
  if (map[key]) return map[key];
  const s = key.replace(/([A-Z])/g, ' $1').trim().toLowerCase();
  return s.charAt(0).toUpperCase() + s.slice(1);
}

export function productAlt(product: Product, variantName?: string) {
  const v = variantName ? `, ${variantName.toLowerCase()} finish` : '';
  return `${product.name}${v}, ${CATEGORY_LABEL[product.category].toLowerCase()} for LPG gas stoves by SR Industries`;
}

/** Royal and Euro series images are photographs on a stove; the rest are cut-outs on white. */
export function isPhoto(src: string) {
  return src.startsWith('/Royal-series/') || src.startsWith('/Euro-series/');
}

/** Transparent studio cut-out made by scripts/cutouts.py; photos are returned unchanged. */
export function cutout(src: string) {
  if (isPhoto(src)) return src;
  return '/parts' + src.replace(/\.png$/, '.webp');
}

